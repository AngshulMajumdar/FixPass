#!/usr/bin/env python3
"""Write benchmarks/RESULTS.md from benchmarks/runs (run_benchmark.py) and fault_observability.json (check_faults.py)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "benchmarks"

# Faults whose repaired text differs from the reference: why the repair is (or is not) equivalent.
NOTES = {
    "gradebook-6": "`copy.length % 2 > 0` is equivalent to `== 1` because lengths are non-negative",
    "gradebook-8": "`w < prev` is equivalent to `w != prev` because the list is sorted by descending score, so `w <= prev`",
    "graph_engine-4": "`dist[v] <= -1` is equivalent to `== -1` because distances are -1 or non-negative",
    "graph_engine-8": "`order.size() <= n - 1` is equivalent to `< n` for ints",
    "inventory-4": "compile stage `=` → `==`, then the String rule gave `\"END\".equals(cmd)`, a null-safe equivalent of `cmd.equals(\"END\")`",
    "inventory-7": "**not fixed**: the search changed `if (c != 0)` to `if (c > 0)`, which passes all visible tests (only 1 of 10 exercises this fault); 7 equal-score alternatives were listed in the report; held-out tests expose it",
    "matrix_lab-5": "`j % 2 < 1` is equivalent to `== 0` because `j >= 0`",
    "matrix_lab-8": "`\"MUL\".equals(cmd)`: null-safe equivalent of `cmd.equals(\"MUL\")`",
}


def main():
    summary = json.loads((B / "runs" / "summary.json").read_text())
    obs = {o["id"]: o for o in json.loads((B / "fault_observability.json").read_text())}
    out = ["# Benchmark results", "",
           "Generated by `scripts/run_benchmark.py` and `scripts/write_results.py`. The engine sees only `visible_tests.json` "
           "(10 tests per case); `validation_tests.json` (40 tests per case) is held out and used only for scoring. "
           "Expected outputs come from the correct `reference.java`. The model-free correction layer: no LLM was used.", "",
           "| Case | Lines | Faults (compile + semantic) | Visible | Held-out | Restored exactly | Equivalent | Not fixed | Candidates run | javac calls | Time (s) | Control unchanged |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    tot = {"faults": 0, "exact": 0, "equiv": 0, "miss": 0, "val": 0, "valn": 0, "secs": 0.0, "cands": 0}
    rows = []
    for r in summary:
        exact = sum(f["outcome"] == "restored" for f in r["faults"])
        miss = sum(1 for f in r["faults"] if f["outcome"] != "restored" and "not fixed" in NOTES.get(f["id"], ""))
        equiv = len(r["faults"]) - exact - miss
        comp = sum(f["category"] == "compile" for f in r["faults"])
        v, vn = map(int, r["validation_passing"].split("/"))
        tot["faults"] += len(r["faults"])
        tot["exact"] += exact
        tot["equiv"] += equiv
        tot["miss"] += miss
        tot["val"] += v
        tot["valn"] += vn
        tot["secs"] += r["seconds"]
        tot["cands"] += int(r["candidates_evaluated"] or 0)
        out.append(f"| {r['case']} | {r['lines']} | {len(r['faults'])} ({comp} + {len(r['faults']) - comp}) | "
                   f"{int(r['visible_passing'])}/10 | {r['validation_passing']} | {exact} | {equiv} | {miss} | "
                   f"{int(r['candidates_evaluated'] or 0)} | {int(r['javac_invocations'])} | {r['seconds']} | "
                   f"{'yes' if r['control_unchanged'] else 'NO'} |")
        rows.append(r)
    out.append(f"| **total** | | {tot['faults']} | 60/60 | {tot['val']}/{tot['valn']} | {tot['exact']} | {tot['equiv']} | "
               f"{tot['miss']} | {tot['cands']} | | {round(tot['secs'], 1)} | 6/6 |")
    out += ["", "Hardware: 2 vCPU Xeon @ 2.1 GHz, 7 GB RAM, OpenJDK 21. Times include JVM start-up for the engine and "
            "the worker; the control runs (unchanged reference programs) are not included.", "",
            "## Per-fault outcome", "",
            "Observability: tests failing when the fault is injected **alone** (visible / held-out). Compile faults are found "
            "by javac and need no tests.", "",
            "| Fault | Kind | Description | Alone: visible / held-out failing | Outcome |", "|---|---|---|---|---|"]
    for r in rows:
        for f in r["faults"]:
            o = obs.get(f["id"], {})
            seen = "compile error" if o.get("alone") == "compile error" else f"{o.get('visible_failed', '?')} / {o.get('validation_failed', '?')}"
            outcome = "restored exactly" if f["outcome"] == "restored" else NOTES.get(f["id"], f["outcome"])
            out.append(f"| {f['id']} | {f['category']} | {f['description']} | {seen} | {outcome} |")
    out += ["", "## How each fault was repaired", "",
            "From each case's `runs/<case>/report.json`: stage, rule or operator, and the line before and after the edit.", ""]
    for r in rows:
        rep = json.loads((B / "runs" / r["case"] / "report.json").read_text())
        out.append(f"### {r['case']}")
        out.append("")
        for c in rep.get("compile_repairs") or []:
            out.append(f"- compile ({c['phase']}), `{c['diagnostic']}` L{int(c['line'])}: {c['rule']}: `{c['before']}` → `{c['after']}`"
                       + (f" ({int(c['tied_alternatives'])} tied alternatives, revisited by the search)" if c.get("tied_alternatives") else ""))
        for s in rep.get("static_rules") or []:
            out.append(f"- static rule L{int(s['line'])}: {s['rule']}: `{s['before']}` → `{s['after']}`")
        for rnd in (rep.get("search") or [])[1:]:
            for e in rnd.get("edits", []):
                extra = ""
                if rnd.get("equal_score_alternatives"):
                    extra = f" ({int(rnd['equal_score_alternatives'])} equal-score alternatives)"
                out.append(f"- search round {int(rnd['round'])}: {e['operator']}: `{e['before']}` → `{e['after']}`{extra}")
        out.append("")
    st = B / "syntax_stress" / "summary.json"
    if st.exists():
        S = json.loads(st.read_text())
        a = S["all"]
        out += ["## Syntax stress test", "",
                f"`scripts/stress_syntax.py`: {S['trials_run']} files, each one of the six reference programs with 1–5 random "
                "corruptions: token deletion, insertion, replacement, swap, duplication, smart quotes and other confusable characters, "
                "unclosed strings and comments, string literals in single quotes, stray characters, dropped line-final tokens. "
                f"{S['with_syntax_error']} of them fail to parse (the others happen to remain valid Java and are excluded). Compile "
                "stages only, no tests. *Token-exact* means the repaired file has the same token sequence as the original program.", "",
                "| Corruptions | Files | Parse after repair | Compile after repair | Token-exact | Lossy (code deleted) |",
                "|---|---|---|---|---|---|"]
        for k, g in S["by_corruption_count"].items():
            out.append(f"| {k} | {g['n']} | {g['parse']} | {g['compiles']} | {g['token_exact']} | {g['lossy']} |")
        out.append(f"| **all** | {a['n']} | {a['parse']} | {a['compiles']} | {a['token_exact']} | {a['lossy']} |")
        out += ["", f"Time per file: median {S['median_seconds']} s, mean {S['mean_seconds']} s, max {S['max_seconds']} s (2 vCPU).", ""]
        if "full_pipeline" in S:
            f = S["full_pipeline"]
            out += [f"Full pipeline with the 10 visible tests on {f['n']} of the files with 1–2 corruptions: "
                    f"{f['exit_0_all_visible_pass']} pass all visible tests, {f['all_heldout_pass']} pass all 40 held-out tests, "
                    f"{f['token_exact']} token-exact, {f['lossy']} lossy (`benchmarks/syntax_stress/full_pipeline.json`).", ""]
    ic = B / "introclassjava" / "summary.json"
    if ic.exists():
        S = json.loads(ic.read_text())
        out += ["## IntroClassJava", "",
                "`scripts/introclassjava.py`. IntroClassJava (Durieux & Monperrus 2016): 297 buggy student programs in six "
                "assignments, each with a blackbox and a whitebox JUnit suite. Repair uses the blackbox suite; the whitebox "
                "suite is held out. The converted tests reproduce the dataset's published pass/fail table exactly "
                "(33 whitebox-ok, 39 blackbox-ok, 225 fail both). No patch touched the generated test driver. "
                "120 s budget per program.", "",
                "| Assignment | Fail blackbox | Plausible patch | Also pass all held-out whitebox tests |", "|---|---|---|---|"]
        for a, g in S["by_assignment"].items():
            out.append(f"| {a} | {g['fail_repair_suite']} | {g['plausible']} | {g['pass_all_heldout']} |")
        out += [f"| **all** | {S['fail_repair_suite']} | {S['plausible_patch']} | {S['plausible_and_pass_all_heldout']} |", "",
                f"The {S['already_pass_repair_suite']} programs that already pass the blackbox suite are returned unchanged. "
                f"Median time per buggy program: {S['median_seconds']} s.", ""]
    qb = B / "quixbugs" / "summary.json"
    qa = B / "quixbugs" / "patch_assessment.json"
    if qb.exists() and qa.exists():
        S = json.loads(qb.read_text())
        A = json.loads(qa.read_text())
        out += ["## QuixBugs (Java)", "",
                "`scripts/quixbugs.py`. QuixBugs (Lin et al. 2017): 40 classic algorithms, each with a one-line bug, specified "
                "by JUnit tests (258 tests after dropping @Ignore). Each JUnit class becomes a stdin-driven driver that prints "
                "the computed values; expected outputs come from QuixBugs' correct versions, and no expected value appears in "
                "the file. Because test inputs still live in the driver, every patch is re-run with the repaired program class "
                "placed into the original, untouched harness; patches that pass only by editing test code are rejected "
                f"(the compiler reported success on {S['compiler_reported_success']}, of which "
                f"{S['compiler_reported_success'] - S['plausible_validated_with_untouched_harness']} edited test inputs). "
                "120 s budget per program.", "",
                "| Outcome | Programs |", "|---|---|",
                f"| Plausible (passes all tests with the untouched harness) | {S['plausible_validated_with_untouched_harness']} / 40 |",
                f"| Identical to the reference fix | {len(A['identical_to_reference'])} |",
                f"| Equivalent to the correct version on random inputs | {len(A['equivalent_on_random_inputs'])} |",
                f"| Overfitted (plausible but wrong on other inputs) | {len(A['overfitted'])} |",
                f"| **Correct** | **{A['correct']} / 40** |", ""]
        for k, v in list(A["equivalent_on_random_inputs"].items()) + list(A["overfitted"].items()):
            out.append(f"- {k}: {v}")
        out.append("")
    if ic.exists() or qb.exists():
        out += ["## Published baselines on the same benchmarks", "",
                "RepairThemAll (Durieux et al., ESEC/FSE 2019) ran 11 Java repair tools with a two-hour budget per bug. "
                "Patched bugs (plausible patches):", "",
                "| | IntroClassJava (297) | QuixBugs (40) |", "|---|---|---|",
                "| Best single tool | 32 (Nopol) | 4 (ARJA, GenProg-A, RSRepair-A, Cardumen) |",
                "| Union of all 11 tools | 62 | 12 |",
                "| JFixPass (120 s per bug) | 50 plausible, 31 pass all held-out tests | 13 plausible, 11 correct |", "",
                "The protocols are not identical (test-suite choice, budgets, adapters), so this is an indication, not a "
                "controlled comparison.", ""]
    (B / "RESULTS.md").write_text("\n".join(out))
    print("wrote", B / "RESULTS.md")


if __name__ == "__main__":
    main()
